<#
.SYNOPSIS
    Downloads the third-party offline databases Whereabouts uses into data/.

.DESCRIPTION
    Whereabouts never looks anything up online while it runs. Instead it
    uses these databases, downloaded here at build time:

      - DB-IP "IP to Country Lite" and "IP to ASN Lite" (MMDB format),
        CC BY 4.0, https://db-ip.com
      - EasyPrivacy tracker list, GPL-3.0-or-later or CC BY-SA 3.0,
        by the EasyList authors, https://easylist.to

    The files are large and change often, so they are not committed to
    Git (see .gitignore). This script records where each file came from,
    its version and its SHA-256 hash in data/SOURCES.generated.txt.

    It uses HTTPS only and sends nothing but the plain download requests.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\update-data.ps1
#>
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$DataDir = Join-Path (Split-Path -Parent $PSScriptRoot) 'data'
$Sources = Join-Path $DataDir 'SOURCES.generated.txt'

function Get-File {
    param([string]$Url, [string]$Destination)
    Invoke-WebRequest -Uri $Url -OutFile $Destination -UseBasicParsing -TimeoutSec 120
    if ((Get-Item $Destination).Length -eq 0) { throw "empty download: $Url" }
}

function Expand-Gzip {
    param([string]$Source, [string]$Destination)
    $in = [IO.File]::OpenRead($Source)
    try {
        $gzip = New-Object IO.Compression.GZipStream($in, [IO.Compression.CompressionMode]::Decompress)
        $out = [IO.File]::Create($Destination)
        try { $gzip.CopyTo($out) } finally { $out.Dispose(); $gzip.Dispose() }
    } finally { $in.Dispose() }
}

function Get-DbIp {
    param([string]$Kind, [string]$Destination)
    # DB-IP publishes monthly; early in a month the new file may not exist yet.
    $now = Get-Date
    foreach ($month in @($now, $now.AddMonths(-1))) {
        $version = $month.ToString('yyyy-MM')
        $url = "https://download.db-ip.com/free/dbip-$Kind-lite-$version.mmdb.gz"
        $gz = "$Destination.gz"
        try {
            Get-File -Url $url -Destination $gz
            Expand-Gzip -Source $gz -Destination $Destination
            Remove-Item $gz
            return @{ Url = $url; Version = $version }
        } catch {
            if (Test-Path $gz) { Remove-Item $gz }
            Write-Host "  not available: $url"
        }
    }
    throw "could not download DB-IP $Kind lite"
}

New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
$lines = @(
    "# Generated by scripts/update-data.ps1 on $((Get-Date).ToUniversalTime().ToString('u'))",
    "# file | version | source | sha256"
)

foreach ($kind in 'country', 'asn') {
    $file = Join-Path $DataDir "dbip-$kind-lite.mmdb"
    Write-Host "DB-IP $kind lite..."
    $info = Get-DbIp -Kind $kind -Destination $file
    $hash = (Get-FileHash -Algorithm SHA256 $file).Hash.ToLower()
    $lines += "dbip-$kind-lite.mmdb | $($info.Version) | $($info.Url) | $hash"
}

Write-Host 'EasyPrivacy...'
$easyPrivacy = Join-Path $DataDir 'easyprivacy.txt'
Get-File -Url 'https://easylist.to/easylist/easyprivacy.txt' -Destination $easyPrivacy
$versionLine = Select-String -Path $easyPrivacy -Pattern '^! Version: (.+)$' | Select-Object -First 1
$version = if ($versionLine) { $versionLine.Matches[0].Groups[1].Value } else { 'unknown' }
$hash = (Get-FileHash -Algorithm SHA256 $easyPrivacy).Hash.ToLower()
$lines += "easyprivacy.txt | $version | https://easylist.to/easylist/easyprivacy.txt | $hash"

Set-Content -Path $Sources -Value $lines -Encoding UTF8
Write-Host ''
Get-Content $Sources | Write-Host
