/** 360 × 180 land mask, one cell per degree: index `(floor(lat)+90)*360 + floor(lon)+180`. */
export function landMask(): Uint8Array {
  const mask = new Uint8Array(360 * 180);
  for (const poly of LAND) {
    let minLon = 180, maxLon = -180, minLat = 90, maxLat = -90;
    for (const [lon, lat] of poly) {
      minLon = Math.min(minLon, lon);
      maxLon = Math.max(maxLon, lon);
      minLat = Math.min(minLat, lat);
      maxLat = Math.max(maxLat, lat);
    }
    for (let lat = Math.floor(minLat); lat < maxLat; lat++) {
      for (let lon = Math.floor(minLon); lon < maxLon; lon++) {
        if (inside(poly, lon + 0.5, lat + 0.5)) mask[(lat + 90) * 360 + (lon + 180)] = 1;
      }
    }
  }
  // Antarctica.
  for (let lat = -90; lat < -67; lat++) mask.fill(1, (lat + 90) * 360, (lat + 91) * 360);
  return mask;
}

/** Whether a latitude/longitude (degrees) is land on the mask. */
export function isLand(mask: Uint8Array, lat: number, lon: number): boolean {
  const row = Math.min(179, Math.max(0, Math.floor(lat + 90)));
  const col = Math.min(359, Math.max(0, Math.floor(lon + 180)));
  return mask[row * 360 + col] === 1;
}

/** Ray casting: is (x, y) inside the polygon? */
function inside(poly: readonly (readonly [number, number])[], x: number, y: number): boolean {
  let result = false;
  for (let a = 0, b = poly.length - 1; a < poly.length; b = a++) {
    const [xa, ya] = poly[a]!;
    const [xb, yb] = poly[b]!;
    if (ya > y !== yb > y && x < ((xb - xa) * (y - ya)) / (yb - ya) + xa) result = !result;
  }
  return result;
}
