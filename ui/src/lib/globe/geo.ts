/** The country's representative point, or null when the code is unknown. */
export function countryCentre(code: string | null): [number, number] | null {
  if (!code) return null;
  const centre = COUNTRY_CENTRES[code.toUpperCase()];
  return centre ? [centre[0], centre[1]] : null;
}

